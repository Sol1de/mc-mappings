//! Minecraft runtime mapping tables, selection and resolution, without a JVM.
//!
//! ```
//! use mc_mappings::{Dataset, Launcher, Loader, MethodId};
//!
//! let tables = Dataset::minecraft_v1()?;
//! let fabric = tables.select("1.21.11", Launcher::Lunar, Loader::Fabric)?;
//! let id: MethodId = "minecraft.client.get_instance".parse()?;
//! let m = fabric.method(&id)?;
//! assert_eq!(m.owner, "net/minecraft/class_310");
//! assert_eq!((m.runtime_name, m.descriptor.as_str(), m.is_static), ("method_1551", "()Lnet/minecraft/class_310;", true));
//! # Ok::<(), Box<dyn std::error::Error>>(())
//! ```
//!
//! [`Dataset::from_json`] checks structure and local constraints, [`Dataset::audit`] the
//! cross-table rules and catalog coverage, and [`Dataset::select`] resolves the semantic symbols
//! of one exact configuration to runtime names and JVM descriptors.

mod audit;
mod identifiers;
mod models;
mod resolver;
mod types;

pub use audit::{AuditReport, ConfigurationCoverage, Problem};
pub use identifiers::{ClassId, FieldId, InvalidIdentifier, MethodId, ProfileId};
pub use models::*;
pub use resolver::{ResolveError, ResolvedClass, ResolvedMember, Selection};
pub use types::{Primitive, Type};

/// The bundled Minecraft v1 tables (`data/minecraft-v1.json`), generated by
/// `mc_mappings_generator`; see `data/README.md` for coverage and provenance.
pub const MINECRAFT_V1: &str = include_str!("../data/minecraft-v1.json");

impl Dataset {
    /// Parses the bundled Minecraft v1 tables ([`MINECRAFT_V1`]).
    pub fn minecraft_v1() -> Result<Self, serde_json::Error> {
        Self::from_json(MINECRAFT_V1)
    }
}

/// The only accepted input alias. Other strings remain exact identities.
pub fn normalize_minecraft_version(version: &str) -> &str {
    match version {
        "1.21.0" => "1.21",
        other => other,
    }
}
